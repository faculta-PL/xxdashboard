function interpolate(template, vars) {
  if (!vars) return template
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (vars[key] != null ? String(vars[key]) : `{${key}}`))
}

export function feedbackT(lang, key, vars) {
  const locale = lang === 'en' ? 'en' : 'fr'
  const parts = String(key || '').split('.')
  let node = dict[locale]
  for (const part of parts) {
    if (node == null || typeof node !== 'object') return key
    node = node[part]
  }
  if (typeof node !== 'string') {
    if (locale !== 'fr') return feedbackT('fr', key, vars)
    return key
  }
  return interpolate(node, vars)
}

