export function formatDateTime(lang, iso) {
  if (!iso) return ''
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return String(iso)
  try {
    return d.toLocaleString(dateLocale(lang), { dateStyle: 'medium', timeStyle: 'short' })
  } catch {
    return String(iso)
  }
}

export function formatDate(lang, iso) {
  if (!iso) return ''
  const raw = String(iso)
  const d = /^\d{4}-\d{2}-\d{2}$/.test(raw)
    ? new Date(`${raw}T12:00:00`)
    : new Date(raw)
  if (Number.isNaN(d.getTime())) return raw
  try {
    return d.toLocaleDateString(dateLocale(lang), { dateStyle: 'medium' })
  } catch {
    return raw
  }
}

function walkKeys(tree, prefix, out) {
  if (!tree || typeof tree !== 'object') return out
  for (const [k, v] of Object.entries(tree)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') out.push(key)
    else if (v && typeof v === 'object' && !Array.isArray(v)) walkKeys(v, key, out)
  }
  return out
}

export function dictKeyList(lang) {
  return walkKeys(dicts[normalizeLang(lang)], '', [])
}

