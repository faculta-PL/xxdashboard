function lookup(tree, key) {
  const parts = String(key || '').split('.')
  let cur = tree
  for (const part of parts) {
    if (cur == null || typeof cur !== 'object') return undefined
    cur = cur[part]
  }
  return typeof cur === 'string' ? cur : undefined
}

export function normalizeLang(value) {
  const raw = String(value || '').trim().toLowerCase()
  if (raw.startsWith('en')) return 'en'
  return 'fr'
}

export function readLang() {
  try {
    return normalizeLang(localStorage.getItem(LANG_KEY) || 'fr')
  } catch {
    return 'fr'
  }
}

export function writeLang(lang) {
  const next = normalizeLang(lang)
  try {
    localStorage.setItem(LANG_KEY, next)
  } catch {
    /* ignore quota */
  }
  return next
}

export function interpolate(template, vars) {
  if (!vars) return template
  return String(template).replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`))
}

export function translate(lang, key, vars) {
  const locale = normalizeLang(lang)
  const raw = lookup(dicts[locale], key) ?? lookup(dicts.fr, key) ?? key
  return interpolate(raw, vars)
}

export function landingPlanPoints(lang, plan) {
  const locale = normalizeLang(lang)
  return LANDING_PLAN_POINTS[locale]?.[plan] || LANDING_PLAN_POINTS.fr[plan] || []
}

export function calendarLabels(lang) {
  const t = (key) => translate(lang, key)
  return {
    weekdays: t('calendar.weekdays').split(','),
    months: t('calendar.months').split(','),
    weekdaysLong: t('calendar.weekdaysLong').split(','),
  }
}

export function dateLocale(lang) {
  return normalizeLang(lang) === 'en' ? 'en-GB' : 'fr-FR'
}

function walkKeys(tree, prefix, out) {
  if (!tree || typeof tree !== 'object') return out
  for (const [k, v] of Object.entries(tree)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') out.push(key)
    else if (v && typeof v === 'object' && !Array.isArray(v)) walkKeys(v, key, out)
  }
  return out
}

export function dictKeyList(lang) {
  return walkKeys(dicts[normalizeLang(lang)], '', [])
}

