export function identityT(lang, key, vars) {
  const locale = lang === 'en' ? 'en' : 'fr'
  const raw = dict[locale][key] ?? dict.fr[key] ?? key
  return String(raw).replace(/\{(\w+)\}/g, (_, name) => (vars && vars[name] != null ? String(vars[name]) : `{${name}}`))
}

export function identityDict(lang) {
  return lang === 'en' ? dict.en : dict.fr
}
