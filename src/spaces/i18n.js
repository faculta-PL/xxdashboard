export function spacesT(lang, key, vars) {
  const locale = lang === 'en' ? 'en' : 'fr'
  const raw = dict[locale][key] ?? dict.fr[key] ?? key
  return String(raw).replace(/\{(\w+)\}/g, (_, name) => (vars && vars[name] != null ? String(vars[name]) : ''))
}

export function spacesRoleLabel(lang, role) {
  return spacesT(lang, `role_${role}`)
}

export function spacesStatusLabel(lang, status) {
  return spacesT(lang, `status_${status || 'active'}`)
}
